interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({} as any);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('locohelp_language');
      if (saved && ['EN', 'HI', 'GU', 'MR', 'BN', 'TA', 'TE', 'KN', 'PA', 'ML'].includes(saved)) {
        return saved as Language;
      }
    } catch {}
    return 'EN';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('locohelp_language', lang);
    } catch {}
  };
  
  const t = (key: string) => {
    return translations[language]?.[key] || translations['EN']?.[key] || key;
  };
  
  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => useContext(LanguageContext);

