export const SUPPORTED_LANGUAGES: { code: Language; label: string; nativeName: string }[] = [
  { code: 'GU', label: 'Gujarati (ગુજરાત સ્પેશિયલ)', nativeName: 'ગુજરાતી' },
  { code: 'HI', label: 'Hindi (हिन्दी)', nativeName: 'हिन्दी' },
  { code: 'EN', label: 'English', nativeName: 'English' }
];

interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
  tr: (en: string, hi: string, gu?: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({} as any);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('locohelp_language');
      if (saved && ['EN', 'HI', 'GU'].includes(saved)) {
        return saved as Language;
      }
    } catch {}
    return 'GU';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('locohelp_language', lang);
    } catch {}
  };
  
  const t = (key: string) => {
    return translations[language]?.[key] || translations['HI']?.[key] || translations['EN']?.[key] || key;
  };

  const tr = (en: string, hi: string, gu?: string) => {
    if (language === 'GU') return gu || hi || en;
    if (language === 'HI') return hi || en;
    return en;
  };
  
  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, tr }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => useContext(LanguageContext);
